Color getAQIColor(int aqi) {
  if (aqi <= 50) return Colors.greenAccent;
  if (aqi <= 100) return const Color(0xFFFFB823);
  if (aqi <= 150) return const Color.fromARGB(255, 172, 97, 1);
  if (aqi <= 200) return Colors.redAccent;
  return Colors.purpleAccent;
}

  String getAQIAdvice(int? aqi) {
    if (aqi == null) return '';
    if (aqi <= 50) return 'Air quality is satisfactory and poses little or no health risk';
    if (aqi <= 100) return 'Air quality is acceptable, some pollutants may be a concern for sensitive people';
    if (aqi <= 150) return 'Sensitive groups may experience health effects';
    if (aqi <= 200) return 'Everyone may begin to experience health effects';
    return 'Health warnings of emergency conditions';
  }

